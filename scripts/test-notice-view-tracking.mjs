import assert from 'node:assert/strict';
import { trackNoticeView } from '../src/utils/noticeViewTracking.js';
const data = new Map();
const storage = { getItem: key => data.get(key), setItem: (key, value) => data.set(key, value) };
let calls = 0;
const increment = async () => { calls++; return true; };
const track = options => trackNoticeView({ storage, increment, ...options });
await Promise.all([track({ noticeId: 1 }), track({ noticeId: 1 })]);
assert.equal(calls, 1, 'concurrent anonymous visits count once');
await track({ noticeId: 1 });
await track({ noticeId: 1, user: { id: 'member' } });
assert.equal(calls, 1, 'refresh and anonymous-to-login do not double count');
await track({ noticeId: 2, user: { id: 'staff', account_role: 'admin' } });
await track({ noticeId: 2, excluded: true });
assert.equal(calls, 1, 'staff and excluded views are skipped');
await track({ noticeId: 2, user: { id: 'member' } });
await track({ noticeId: 2, user: { id: 'member' } });
assert.equal(calls, 2, 'public link and modal share member deduplication');
await track({ noticeId: 3, increment: async () => null });
await track({ noticeId: 3 });
assert.equal(calls, 3, 'failed writes can be retried');
await assert.rejects(track({ noticeId: 4, increment: async () => { throw new Error('offline'); } }));
await track({ noticeId: 4 });
assert.equal(calls, 4, 'rejected writes can be retried');
const blocked = { getItem() { throw new Error('blocked'); }, setItem() { throw new Error('blocked'); } };
assert.equal(await track({ noticeId: 5, storage: blocked }), true);
console.log('PASS notice view tracking: public/member, deduplication, exclusions, failures, disabled storage');
