import assert from 'node:assert/strict';
import { getProgramButtons, normalizeProgramButton, buttonHasTeams, buttonHasQuestions,
    isProgramButtonVisible, validateProgramButtons } from '../src/features/programs/programButtons.js';

const guide = normalizeProgramButton({ id: 'prayer', name: '디너처치 기도문', content: '사랑의 하나님.\n직접 작성한 기도문입니다.' });
const discussion = normalizeProgramButton({ id: 'discussion', template: 'QUESTIONS', name: '오늘의 나눔', questions: ['직접 만든 질문 1', '직접 만든 질문 2'], trigger: 'end_time' });
const teams = normalizeProgramButton({ id: 'teams', template: 'TEAM', name: '조별 모임', group_count: 7 });
const program = { program_date: '2026-10-23T09:00:00Z', program_duration: '1시간 30분', guest_properties: { program_buttons: [guide, discussion, teams] } };
const buttons = getProgramButtons(program);
assert.equal(buttons.length, 3);
assert.equal(buttons[1].question_display_mode, 'LIST', 'all existing questions default to list display');
assert.equal(normalizeProgramButton({ template: 'QUESTIONS', question_display_mode: 'invalid' }).question_display_mode, 'LIST');
assert.equal(getProgramButtons({ guest_properties: { program_buttons: [{ ...discussion, question_display_mode: 'RANDOM' }] } })[0].question_display_mode, 'RANDOM', 'the administrator display setting survives loading');
assert.equal(buttons[0].content, guide.content);
assert.equal(buttonHasQuestions(buttons[0]), false, 'a DIY prayer button must not inherit discussion questions');
assert.equal(buttonHasTeams(buttons[0]), false);
assert.deepEqual(buttons[1].questions, discussion.questions);
assert.deepEqual(buttons[1].questions[0], { question: '직접 만든 질문 1', description: '' }, 'existing question strings migrate without losing text');
const described = normalizeProgramButton({ template: 'QUESTIONS', questions: [{ question: '요즘 학교에서 어떻게 지내?', description: '소소한 행복을 느꼈던 하루 등 편하게 나눠보자.' }] });
assert.equal(described.questions[0].description, '소소한 행복을 느꼈던 하루 등 편하게 나눠보자.');
assert.equal(validateProgramButtons([described]), '');
assert.match(validateProgramButtons([{ ...described, questions: [{ question: '', description: '설명만 입력' }] }]), /질문/);
assert.equal(buttons[2].group_count, 7);
assert.equal(validateProgramButtons(buttons), '');
assert.equal(isProgramButtonVisible(buttons[1], program, Date.parse('2026-10-23T10:29:59Z')), false);
assert.equal(isProgramButtonVisible(buttons[1], program, Date.parse('2026-10-23T10:30:00Z')), true, 'end-time buttons remain accessible after program end');
assert.equal(isProgramButtonVisible({ ...guide, offset_minutes: 60 }, program, Date.parse('2026-10-23T08:00:00Z')), true);
assert.equal(isProgramButtonVisible({ ...guide, enabled: false }, { ...program, program_status: 'COMPLETED' }), false);
assert.equal(isProgramButtonVisible(guide, { ...program, program_status: 'CANCELLED' }), false);
assert.deepEqual(getProgramButtons({ ...program, program_buttons: [] }), [], 'removing all buttons overrides persisted/legacy settings');
const legacy = { enable_post_program_button: true, post_program_button_name: '기존 버튼', post_program_button_content: '기존 안내', enable_group_assignment: true, enable_random_questions: true, random_questions: ['기존 질문'], group_count: 5 };
assert.equal(getProgramButtons(legacy)[0].template, 'TEAM_QUESTIONS');
assert.equal(getProgramButtons(legacy)[0].group_count, 5);
assert.deepEqual(getProgramButtons({ ...legacy, program_buttons: [] }), []);
assert.match(validateProgramButtons([{ ...guide, link: 'javascript:alert(1)' }]), /http/);
assert.match(validateProgramButtons([{ ...discussion, questions: [] }]), /질문/);
assert.match(validateProgramButtons([{ ...discussion, content: '기본형에서 작성했던 내용', questions: [] }]), /질문/, 'hidden custom content must not satisfy a question template');
assert.equal(validateProgramButtons([{ ...teams, link: '이전 기본형의 미완성 링크' }]), '', 'inactive custom fields must not block saving a team template');
assert.match(validateProgramButtons([{ ...discussion, questions: ['좋은 질문', ''] }]), /빈 나눔/);
const changed = getProgramButtons(program); changed[1].questions[0].question = '수정된 질문';
assert.equal(program.guest_properties.program_buttons[1].questions[0].question, '직접 만든 질문 1');
console.log('PASS: DIY content, independent button settings, legacy migration, validation, and per-button visibility');
