import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import pg from 'pg';

// Synthetic, isolated database only. The optional real-server mode is pinned
// to a temporary loopback database and never accepts a remote URL.
const db = await (async () => {
    if (!process.argv.includes('--real-postgres')) return new PGlite();
    const client = new pg.Client({ host: '127.0.0.1', port: 55432, user: 'postgres',
        database: 'codex_staff_20260929', connectionTimeoutMillis: 3000,
        application_name: 'codex-isolated-staff-program-walkins-test' });
    await client.connect();
    return { exec: statement => client.query(statement), query: (statement, values) => client.query(statement, values),
        close: () => client.end() };
})();
const ids = Array.from({ length: 5 }, () => crypto.randomUUID());
const sessionId = crypto.randomUUID();
const secondSessionId = crypto.randomUUID();
const sql = path => db.exec(readFileSync(new URL(path, import.meta.url), 'utf8'));
const api = readFileSync(new URL('../src/api/staffProgramWalkInsApi.js', import.meta.url), 'utf8');
assert.match(api, /add_staff_program_walkins/);
assert.match(api, /add_staff_program_session_walkins/);
assert.match(api, /staff_program_walkins/);
assert.match(api, /staff_program_session_walkins/);
assert.match(api, /cancel_staff_program_session_application/);
assert.match(api, /staff_program_session_cancellations/);
assert.doesNotMatch(api, /\.from\(['"](?:notice_responses|daily_program_session_responses)['"]\)/);

try {
    await db.exec(`
        CREATE ROLE anon;
        CREATE ROLE authenticated;
        CREATE FUNCTION public.is_current_staff() RETURNS boolean LANGUAGE sql AS $$
            SELECT COALESCE(current_setting('test.admin',true),'false') = 'true'
        $$;
        CREATE TABLE public.users (id uuid PRIMARY KEY);
        CREATE TABLE public.notices (
            id bigint PRIMARY KEY, title text NOT NULL, category text,
            is_challenge boolean, is_recruiting boolean
        );
        CREATE TABLE public.notice_responses (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            notice_id bigint REFERENCES public.notices(id), user_id uuid REFERENCES public.users(id),
            status text NOT NULL CHECK(status IN ('JOIN','WAITLIST','DECLINE','UNDECIDED')),
            is_attended boolean, created_at timestamptz NOT NULL DEFAULT now(),
            application_answers jsonb NOT NULL DEFAULT '{}'::jsonb,
            application_form_revision integer, application_form_snapshot jsonb,
            UNIQUE(notice_id,user_id)
        );
        CREATE TABLE public.daily_program_sessions (
            id uuid PRIMARY KEY, notice_id bigint REFERENCES public.notices(id),
            capacity integer, voided_at timestamptz
        );
        CREATE TABLE public.daily_program_session_responses (
            session_id uuid REFERENCES public.daily_program_sessions(id),
            user_id uuid REFERENCES public.users(id),
            status text NOT NULL CHECK(status IN ('JOIN','WAITLIST','CANCELLED')),
            is_attended boolean NOT NULL DEFAULT false,
            created_at timestamptz NOT NULL DEFAULT now(), cancelled_at timestamptz,
            application_answers jsonb NOT NULL DEFAULT '{}'::jsonb,
            application_form_revision integer, application_form_snapshot jsonb,
            PRIMARY KEY(session_id,user_id)
        );
    `);
    await sql('../supabase/manual/proposals/20260929_program_application_cancellation_history.sql');
    await sql('../supabase/manual/proposals/20260929_session_application_attempt_history.sql');
    await sql('../supabase/manual/proposals/20260929_staff_program_walkins.sql');

    await db.query(`INSERT INTO public.notices(id,title,category,is_challenge,is_recruiting)
        VALUES(1,'현장 추가 시험','PROGRAM',false,true)`);
    await db.query('INSERT INTO public.daily_program_sessions(id,notice_id,capacity) VALUES($1,1,1)', [sessionId]);
    await db.query('INSERT INTO public.daily_program_sessions(id,notice_id,capacity) VALUES($1,1,1)', [secondSessionId]);
    for (const id of ids.slice(0, 4)) await db.query('INSERT INTO public.users(id) VALUES($1)', [id]);
    for (const [index, status] of ['JOIN', 'WAITLIST', 'CANCELLED'].entries()) {
        await db.query(`INSERT INTO public.notice_responses
            (notice_id,user_id,status,is_attended,cancelled_at,application_answers,
             application_form_revision,application_form_snapshot)
            VALUES(1,$1,$2,false,$3,$4::jsonb,2,'{"questions":[]}'::jsonb)`,
        [ids[index], status, status === 'CANCELLED' ? new Date() : null,
            JSON.stringify({ prior: index })]);
        await db.query(`INSERT INTO public.daily_program_session_responses
            (session_id,user_id,status,is_attended,cancelled_at,application_answers,
             application_form_revision,application_form_snapshot)
            VALUES($1,$2,$3,false,$4,$5::jsonb,2,'{"questions":[]}'::jsonb)`,
        [sessionId, ids[index], status, status === 'CANCELLED' ? new Date() : null,
            JSON.stringify({ prior: index })]);
    }
    await db.query(`INSERT INTO public.daily_program_session_responses
        (session_id,user_id,status,is_attended) VALUES($1,$2,'JOIN',false),($1,$3,'WAITLIST',false)`,
    [secondSessionId, ids[0], ids[1]]);

    await db.exec('SET ROLE anon');
    await assert.rejects(db.query('SELECT public.add_staff_program_walkins(1,$1::uuid[])',
        [[ids[0]]]), error => error.code === '42501');
    await assert.rejects(db.query('SELECT public.cancel_staff_program_session_application($1,$2)',
        [secondSessionId, ids[0]]), error => error.code === '42501');
    await db.exec('RESET ROLE');
    await db.exec('SET ROLE authenticated');
    await assert.rejects(db.query('SELECT id FROM public.program_application_attempt_history'),
        error => error.code === '42501');
    await assert.rejects(db.query('SELECT id FROM public.program_session_application_attempt_history'),
        error => error.code === '42501');
    await assert.rejects(db.query('SELECT public.add_staff_program_walkins(1,$1::uuid[])',
        [[ids[0]]]), /관리자 권한/);
    await assert.rejects(db.query(`INSERT INTO public.staff_program_session_walkins
        (session_id,user_ids) VALUES($1,$2::uuid[])`, [sessionId, [ids[0]]]), /관리자 권한/);
    await assert.rejects(db.query('SELECT public.cancel_staff_program_session_application($1,$2)',
        [secondSessionId, ids[0]]), /관리자 권한/);
    await db.query("SELECT set_config('test.admin','true',false)");
    await assert.rejects(db.query('SELECT public.add_staff_program_walkins(1,$1::uuid[])',
        [[]]), /참여자 목록/);
    const whole = await db.query(`INSERT INTO public.staff_program_walkins
        (notice_id,user_ids) VALUES(1,$1::uuid[]) RETURNING added_count`,
    [[ids[0], ids[1], ids[2], ids[2]]]);
    assert.equal(whole.rows[0].added_count, 3);
    const session = await db.query('SELECT public.add_staff_program_session_walkins($1,$2::uuid[]) AS result',
        [sessionId, ids.slice(0, 3)]);
    assert.equal(session.rows[0].result.count, 3);

    // One bad user rolls back the entire multi-person operation.
    await assert.rejects(db.query('SELECT public.add_staff_program_walkins(1,$1::uuid[])',
        [[ids[3], ids[4]]]), error => error.code === '23503');
    await assert.rejects(db.query('SELECT public.add_staff_program_session_walkins($1,$2::uuid[])',
        [sessionId, [ids[3], ids[4]]]), error => error.code === '23503');
    assert.equal((await db.query(`INSERT INTO public.staff_program_session_cancellations
        (session_id,user_id) VALUES($1,$2) RETURNING status`,
    [secondSessionId, ids[0]])).rows[0].status, 'CANCELLED');
    assert.equal((await db.query('SELECT public.cancel_staff_program_session_application($1,$2) AS result',
        [secondSessionId, ids[0]])).rows[0].result.status, 'CANCELLED');
    await db.query("SELECT set_config('test.admin','false',false)");
    await db.exec('RESET ROLE');

    const wholeRows = (await db.query(`SELECT user_id,status,is_attended,application_answers,
        application_form_revision,application_form_snapshot FROM public.notice_responses
        WHERE notice_id=1`)).rows;
    const sessionRows = (await db.query(`SELECT user_id,status,is_attended,application_answers,
        application_form_revision,application_form_snapshot FROM public.daily_program_session_responses
        WHERE session_id=$1`, [sessionId])).rows;
    for (const rows of [wholeRows, sessionRows]) {
        assert.equal(rows.length, 3, 'a failed batch must leave no partial new user');
        for (const row of rows) {
            assert.equal(row.status, 'JOIN');
            assert.equal(row.is_attended, true);
        }
        for (const index of [0, 1]) {
            const row = rows.find(item => item.user_id === ids[index]);
            assert.deepEqual(row.application_answers, { prior: index },
                'active applicants retain their original answers');
        }
        const readded = rows.find(item => item.user_id === ids[2]);
        assert.deepEqual(readded.application_answers, {},
            'a new walk-in must not inherit a cancelled attempt answer');
        assert.equal(readded.application_form_revision, null);
        assert.equal(readded.application_form_snapshot, null);
    }
    const wholeHistory = (await db.query(`SELECT application_answers FROM
        public.program_application_attempt_history WHERE notice_id=1 AND user_id=$1`, [ids[2]])).rows;
    const sessionHistory = (await db.query(`SELECT application_answers FROM
        public.program_session_application_attempt_history WHERE session_id=$1 AND user_id=$2`,
    [sessionId, ids[2]])).rows;
    assert.deepEqual(wholeHistory.map(row => row.application_answers), [{ prior: 2 }]);
    assert.deepEqual(sessionHistory.map(row => row.application_answers), [{ prior: 2 }]);
    const promotedRows = (await db.query(`SELECT user_id,status FROM public.daily_program_session_responses
        WHERE session_id=$1`, [secondSessionId])).rows;
    assert.equal(promotedRows.find(row => row.user_id === ids[0])?.status, 'CANCELLED');
    assert.equal(promotedRows.find(row => row.user_id === ids[1])?.status, 'JOIN');
    console.log('staff walk-ins: whole/session atomic batch, staff guard, answer history, session cancellation and promotion');
} finally {
    await db.close();
}
