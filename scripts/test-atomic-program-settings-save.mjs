import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const surveyVersion = '11111111-1111-4111-8111-111111111111';
const payload = (title, form = { questions: [] }) => ({
    title, category: 'PROGRAM', application_form: form,
    guest_properties: { enable_feedback: true },
    is_challenge: true, challenge_format: 'ONLINE', program_status: 'ACTIVE',
});
try {
    await db.exec(`
        CREATE ROLE anon;
        CREATE ROLE authenticated;
        CREATE FUNCTION public.is_current_staff() RETURNS boolean LANGUAGE sql AS $$
            SELECT COALESCE(current_setting('test.admin',true),'false')='true'
        $$;
        CREATE TABLE public.notices (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            title text NOT NULL, category text NOT NULL, application_form jsonb,
            application_form_revision integer NOT NULL DEFAULT 0,
            guest_properties jsonb, is_challenge boolean, challenge_format text,
            program_status text
        );
        CREATE TABLE public.survey_marks (notice_id bigint, definition jsonb);
        CREATE TABLE public.mission_marks (notice_id bigint, missions jsonb);
        CREATE TABLE public.survey_links (notice_id bigint, event text, enabled boolean);
        CREATE FUNCTION public.validate_program_application_form(p_form jsonb)
        RETURNS void LANGUAGE plpgsql AS $$ BEGIN
            IF jsonb_typeof(p_form->'questions') IS DISTINCT FROM 'array' THEN
                RAISE EXCEPTION 'Invalid application form';
            END IF;
        END $$;
        CREATE FUNCTION public.revise_form() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN
            IF TG_OP='INSERT' THEN NEW.application_form_revision:=1;
            ELSIF NEW.application_form IS DISTINCT FROM OLD.application_form THEN
                NEW.application_form_revision:=OLD.application_form_revision+1;
            ELSE NEW.application_form_revision:=OLD.application_form_revision;
            END IF;
            RETURN NEW;
        END $$;
        CREATE TRIGGER revise_form BEFORE INSERT OR UPDATE ON public.notices
            FOR EACH ROW EXECUTE FUNCTION public.revise_form();
        CREATE FUNCTION public.save_program_survey(bigint,uuid,uuid,jsonb)
        RETURNS jsonb LANGUAGE plpgsql AS $$ BEGIN
            IF $4->>'fail'='true' THEN RAISE EXCEPTION 'survey failure'; END IF;
            INSERT INTO public.survey_marks VALUES($1,$4);
            RETURN jsonb_build_object('version_id','${surveyVersion}');
        END $$;
        CREATE FUNCTION public.sync_challenge_missions(bigint,text,jsonb)
        RETURNS void LANGUAGE plpgsql AS $$ BEGIN
            IF $3 @> '[{"fail":true}]'::jsonb THEN RAISE EXCEPTION 'mission failure'; END IF;
            INSERT INTO public.mission_marks VALUES($1,$3);
        END $$;
    `);
    await db.exec(readFileSync(new URL('../supabase/manual/proposals/20260930_atomic_program_settings_save.sql', import.meta.url), 'utf8'));
    await db.exec('SET ROLE authenticated');
    await assert.rejects(db.query(`SELECT public.save_program_settings_atomic(
        NULL,$1::jsonb,NULL,NULL,NULL)`, [JSON.stringify(payload('권한 없음'))]), /관리자 권한/);
    await db.query("SELECT set_config('test.admin','true',false)");
    await assert.rejects(db.query(`SELECT public.save_program_settings_atomic(
        NULL,$1::jsonb,NULL,NULL,NULL)`, [JSON.stringify({ ...payload('잘못된 값'), id: 42 })]), /저장할 수 없는/);
    await assert.rejects(db.query(`SELECT public.save_program_settings_atomic(
        NULL,$1::jsonb,NULL,$2::jsonb,'[]'::jsonb)`, [JSON.stringify(payload('설문 실패')),
        JSON.stringify({ definition: { fail: true } })]), /survey failure/);
    await assert.rejects(db.query(`SELECT public.save_program_settings_atomic(
        NULL,$1::jsonb,NULL,$2::jsonb,$3::jsonb)`, [JSON.stringify(payload('미션 실패')),
        JSON.stringify({ definition: { title: '설문' } }), JSON.stringify([{ fail: true }])]), /mission failure/);
    await db.exec('RESET ROLE');
    assert.equal((await db.query('SELECT count(*)::integer AS count FROM public.notices')).rows[0].count, 0);
    assert.equal((await db.query('SELECT count(*)::integer AS count FROM public.survey_marks')).rows[0].count, 0);
    await db.exec('SET ROLE authenticated');
    const saved = (await db.query(`INSERT INTO public.program_settings_save_requests
        (notice,survey,missions) VALUES($1::jsonb,$2::jsonb,$3::jsonb)
        RETURNING saved_notice_id,application_form_revision,saved_survey`, [
        JSON.stringify(payload('처음 저장')),
        JSON.stringify({ definition: { title: '설문' } }),JSON.stringify([{ title: '미션' }]),
    ])).rows[0];
    assert.equal(saved.application_form_revision, 1);
    assert.deepEqual(saved.saved_survey, { version_id: surveyVersion });
    await assert.rejects(db.query(`SELECT public.save_program_settings_atomic(
        $1,$2::jsonb,0,NULL,NULL)`, [saved.saved_notice_id,
        JSON.stringify(payload('오래된 화면'))]), /설정이 변경/);
    const changed = (await db.query(`SELECT public.save_program_settings_atomic(
        $1,$2::jsonb,1,NULL,'[]'::jsonb) AS result`, [saved.saved_notice_id,
        JSON.stringify(payload('수정 완료', { questions: [{ id: 'q1' }] }))])).rows[0].result;
    assert.equal(changed.application_form_revision, 2);
    await db.exec('RESET ROLE');
    const notice = (await db.query('SELECT * FROM public.notices WHERE id=$1', [saved.saved_notice_id])).rows[0];
    assert.equal(notice.title, '수정 완료');
    assert.equal(notice.guest_properties.survey_version_id, surveyVersion);
    assert.equal((await db.query('SELECT count(*)::integer AS count FROM public.survey_marks')).rows[0].count, 1);
    assert.equal((await db.query('SELECT count(*)::integer AS count FROM public.mission_marks')).rows[0].count, 2);
    console.log('atomic program settings save: staff guard, allowlist, rollback, revision, RPC relation fallback');
} finally {
    await db.close();
}
