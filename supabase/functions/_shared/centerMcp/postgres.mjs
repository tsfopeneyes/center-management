import { createSourceReader } from '../operationStatistics/source.mjs';
import { StatisticsError } from '../operationStatistics/policy.mjs';
const quote = name => '"' + name + '"';
const textFields = new Set(['created_at', 'program_date', 'session_date', 'attendance_date', 'voided_at']);

// pool MUST connect as the reviewed restricted reader; no service role bearer
// or frontend token is forwarded to the DB. No schema/grant/mutation SQL here.
async function snapshot(pool, operation) {
    if (typeof pool?.connect !== 'function') throw new StatisticsError('not_configured');
    const client = await pool.connect(); let started = false, discard = false;
    try {
        await client.query('BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY'); started = true;
        const role = await client.query('SELECT current_user AS role');
        if (role.rows?.length !== 1 || role.rows[0].role !== 'center_statistics_reader') throw new StatisticsError('not_configured');
        await client.query("SET LOCAL statement_timeout = '5000ms'");
        await client.query("SET LOCAL idle_in_transaction_session_timeout = '15000ms'");
        await client.query("SET LOCAL TIME ZONE 'UTC'");
        return await operation(client);
    } catch { throw new StatisticsError('source_incomplete'); }
    finally {
        if (started) try { await client.query('ROLLBACK'); } catch { discard = true; }
        client.release(discard);
    }
}

export function createPostgresSourceReader({ pool } = {}) {
    return window => {
        if (!Number.isFinite(Date.parse(window?.asOf))) throw new StatisticsError('source_incomplete');
        return snapshot(pool, async client => createSourceReader({ readPage: async plan => {
        // Plans are generated by createSourceReader, never HTTP request data.
        const values = [], conditions = [];
        const parameter = value => { values.push(value); return '$' + values.length; };
        for (const [field, operator, value] of plan.filters) conditions.push(`${quote(field)} ${{ gte: '>=', lt: '<', eq: '=' }[operator]} ${parameter(value)}`);
        if (plan.table === 'logs') conditions.push(`"created_at" <= ${parameter(window.asOf)}`);
        if (plan.after) conditions.push(`ROW(${plan.order.map(quote).join(',')}) > ROW(${plan.after.map(parameter).join(',')})`);
        const columns = plan.select.split(',').map(field => textFields.has(field) ? `${quote(field)}::text AS ${quote(field)}` : quote(field));
        const sql = `SELECT ${columns.join(',')} FROM public.${quote(plan.table)}${conditions.length ? ' WHERE ' + conditions.join(' AND ') : ''} ORDER BY ${plan.order.map(quote).join(',')} LIMIT ${parameter(plan.limit + 1)}`;
        const { rows } = await client.query(sql, values);
        return { complete: true, rows: rows.slice(0, plan.limit), hasMore: rows.length > plan.limit };
        } })(window));
    };
}

export function createAccountStateReader({ pool } = {}) {
    return authUserId => snapshot(pool, async client => {
        const { rows } = await client.query(`SELECT a.auth_user_id::text AS "authUserId", a.profile_id::text AS "profileId",
            a.mapping_verified AS "mappingVerified", a.status, a.must_change_password AS "mustChangePassword",
            a.credential_version AS "credentialVersion", r.role, r.enabled AS "roleEnabled"
            FROM account_security.accounts a JOIN account_security.account_roles r ON r.profile_id=a.profile_id
            WHERE a.auth_user_id=$1::uuid`, [authUserId]);
        if (rows.length > 1) throw new StatisticsError('source_incomplete');
        return rows[0] || null;
    });
}
