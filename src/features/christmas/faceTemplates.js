export function drawFaceTemplate(context, template, size) {
    const scale = size / 480
    context.save()
    context.scale(scale, scale)
    context.strokeStyle = '#292724'
    context.lineWidth = 7
    context.lineJoin = 'round'
    context.stroke(new Path2D(template.outline))
    context.restore()
}
